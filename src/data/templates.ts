/** Навык: ступени по порядку; boss — последняя ступень контрольная. */
function sk(key: string, title: string, stages: TplGoal[][], extra: { boss?: boolean; metric?: TplMetric; requires?: TplSkill['requires'] } = {}): TplSkill {
  return {
    key, title,
    stages: stages.map((goals, i) => ({ stage: i + 1, goals, ...(extra.boss && i === stages.length - 1 ? { boss: true } : {}) })),
    ...(extra.metric ? { metric: extra.metric } : {}),
    ...(extra.requires ? { requires: extra.requires } : {}),
  };
}

