const uniq = (xs: string[]) => [...new Map(xs.map((x) => [x.toLowerCase().replace(/ё/g, 'е').trim(), x.trim()])).values()];

// ---------- из путей ----------
const tplSkills: { title: string; area: string; goals: string[] }[] = [];
const tplBranches = new Map<string, string[]>();
for (const t of TEMPLATES) {
  for (const a of t.areas) {
    const walk = (b: TplBranch) => {
      tplBranches.set(a.title, [...(tplBranches.get(a.title) ?? []), b.title]);
      for (const s of b.skills ?? []) tplSkills.push({ title: s.title, area: a.title, goals: s.stages.flatMap((st) => st.goals.map((g) => g.title)) });
      b.branches?.forEach(walk);
    };
    a.branches.forEach(walk);
  }
}

